def rotateClock(state: State, face_name: str) -> State:
  newFace = rotateClockData(getFace(face_name, state))      # returns a rotated tuple
  newState = setFace(face_name, newFace, state)              # returns the new state
  adjacent = adjacentEdges(face_name)                       # returns a list of tuples (with face name)


# i indicates which face (taken from adjacentEdges)
  for face, positions, face2, positions2 in adjacent:
    original = getFace(face, state)                         # get our current tuple
    values = [original[i] for i in positions]
    newValues = list(getFace(face2, newState))              # variable for list of empty tuple
  # populate our new empty tuple with values from adjacentEdges
    for j, pos in enumerate(positions2):
      newValues[pos] = values[j]
    newState = setFace(face2, tuple(newValues), newState) # finalize rotation
  return newState

def rotateCounterClock(state: State, face_name: str) -> State:
  newState = rotateClock(state, face_name)
  newState = rotateClock(newState, face_name)
  newState = rotateClock(newState, face_name)
  return newState


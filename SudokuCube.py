def randomizer(state:State,numMoves:int) ->  tuple[State, list[tuple[str, int]]]:
  moves = ['F','U','D','L','R','B']
  rotation = [0,1]  # 0: clockwise 1: counterClockwise
  listOfMoves = []
  last_face = None
  last_dir = None
  for i in range(numMoves):
    while True:
      face = random.choice(moves)
      direction = random.choice(rotation)
      if not (last_face == face and last_dir is not None and direction != last_dir):
        break

    listOfMoves.append((face,direction))
    if direction  == 1:
      state = rotateCounterClock(state,face)
    else:
      state = rotateClock(state,face)
    last_face = face
    last_dir = direction
  return state, listOfMoves


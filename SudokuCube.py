def CWRandomizer(state:State,numMoves:int) ->  tuple[State, list[tuple[str, int]]]: # Randomizes only clockwise per Hint. Making A* easier to solve
  moves = ['F','U','D','L','R','B']
  sequenceOfMoves = []
  last = None
  for i in range(numMoves):  # Does not need Check for Last move since CCW is impossible for next move
    face = random.choice(moves)
    if last is not None and face == last:
      face = random.choice([m for m in moves if m != last])
    state = rotateClock(state,face)
    sequenceOfMoves.append((face,0))
    last = face
  return state, sequenceOfMoves

def tupleToBytes(state: State) -> bytes:
  ouput = bytearray(27) # mutable seques of bytes
  for i in range(27): #27 since 2 stickers stored in one byte
    evenInt = state[2*i] & 0x0F
    oddInt = state[2*i+1] & 0x0F
    ouput[i] = (evenInt << 4) | oddInt
  return bytes(ouput)   # returns even digit then odd digit in order

def bytesToTuple (bytesX: bytes) -> State:
  state = []
  for byte in bytesX:
    state.append((byte >> 4) & 0x0F)  #shifts to grab first sticker
    state.append(byte & 0x0F)    # grabs second
  return tuple(state)

from collections import OrderedDict
class HeuristicLRU:
  def __init__(self, max_size: int = 1000000):
    self.max_size = max_size
    self.store = OrderedDict() # keep track elements inserted in cache
    self.hits = 0 # how many times accessed
    self.misses = 0 # how many times not accessed
  def get(self, key):
    try: # try except since Key error is apart OrderedDict
      value = self.store.pop(key)  #removes the key
      self.store[key] = value # Mark it at end / MRU(Most-Recently-Used)
      self.hits += 1
      return value
    except KeyError:
      self.misses += 1
      return None
  def put(self, key, value):
    if key in self.store: # if in cache
      self.store.pop(key) # removes key
    elif len(self.store) >= self.max_size: # if cahce is at max
      self.store.popitem(last=False) # evict the LRU
    self.store[key] = value # add key as MRU

  def reSize(self, new_size: int):
    while len(self.store) > new_size:
      self.store.popitem(last=False) # continuously evicts LRU elements untill new size

MAINCACHE = HeuristicLRU(1000000)
def HeuristicByCache(compTuple:bytes ) ->int:
  value = MAINCACHE.get(compTuple) # tries to get it from cache
  if value is not None:
    return value #if in cache
  hvalue = heuristic(bytesToTuple(compTuple)) # intensive computation
  MAINCACHE.put(compTuple, hvalue) # adds to cache
  return hvalue

import psutil

class ResourceMonitor:
  def __init__(self, maxMemoryUsage=0.95, minFreeMemoryMb=1024,checkEvery = 2048):
    self.maxMemoryUsage = maxMemoryUsage
    self.minFreeMemoryMb = minFreeMemoryMb
    self._checkCount = 0
    self.checkEvery = int(checkEvery)
  def shouldTerminateSearch(self) -> bool: # if too much memeory
    self._checkCount += 1
    if self._checkCount % self.checkEvery != 0:
      return False

    # Get current memory statistics
    memoryInfo = psutil.virtual_memory()

    # Calculate how much memory is currently being used
    memoryUsageFraction = (memoryInfo.total - memoryInfo.available) / memoryInfo.total
    availableMb = memoryInfo.available / (1024 * 1024)

    # stop if either is exceeded
    usageTooHigh = memoryUsageFraction >= self.maxMemoryUsage
    freeMemoryTooLow = availableMb < self.minFreeMemoryMb

    return usageTooHigh or freeMemoryTooLow

import time
import heapq

def aStarMethod(randomizedState:State , resourceMonitor:ResourceMonitor) -> dict:
  searchStartTimer = time.perf_counter()

  possibleMoves = ['F','U','D','L','R','B']

  initialH = heuristic(randomizedState)  # inital heuristic

  if(initialH == 0):
    return {'Solved' :True , 'moves': [] , 'nodesExpanded': 0 , 'finalLayerNodes' : 1 , 'searchTime' : 0.0  }

  startKey = tupleToBytes(randomizedState) # config to smaller data struct
  frontier = [(initialH,initialH,0,startKey)]  # g is 0 at start f=g+h = 0+h = h.
  # Our tie breaker is linear increasing counter; meaning first explored nodes have priority if f and h is equal

  bestCostToState = {startKey:0}  # g is 0

  parentRelations = {startKey:(None,None)}  # (Parent , Move Used)

  totalNodesExpanded = 0
  tieBreakerCount = 1

  currentFinalLayer = initialH
  nodesInCurrentLayer = 0


  while frontier:  # while goal = false
    if resourceMonitor.shouldTerminateSearch():
      return {'Solved' :False , 'moves': [] , 'nodesExpanded': totalNodesExpanded , 'finalLayerNodes' : nodesInCurrentLayer , 'searchTime' : time.perf_counter() -searchStartTimer }  # Memory condition

    fcost,hcost,tieC,currentKey = heapq.heappop(frontier)  # node = lowest(f=g+h)

    if fcost != currentFinalLayer:  # track which f cost
      currentFinalLayer = fcost
      nodesInCurrentLayer = 0
    nodesInCurrentLayer += 1

    actualGCost = bestCostToState.get(currentKey,float('inf')) # skipping outdated entries
    if fcost - hcost > actualGCost:
      continue  # ignore old entries with worse path

    currentState = bytesToTuple(currentKey) # to process heurisitc

    if hcost==0:
      solutionMoves = []
      reconstruction = currentKey
      while parentRelations[reconstruction][0] is not None:
        parentKey,moveUsed = parentRelations[reconstruction]
        solutionMoves.append(moveUsed)
        reconstruction = parentKey
      solutionMoves.reverse()  #start to goal actions


      return {'Solved' :True , 'moves': solutionMoves , 'nodesExpanded': totalNodesExpanded , 'finalLayerNodes' : nodesInCurrentLayer , 'searchTime' : time.perf_counter() -searchStartTimer }  # Memory condition

    totalNodesExpanded += 1 # count each expanded node

    lastMoveUsed = parentRelations[currentKey][1]  # generating all possible successors

    for move in possibleMoves:  # push all children node
      if lastMoveUsed is not None and move == lastMoveUsed:  # avoid repating the same face immediatley
        continue
      nextState = rotateCounterClock(currentState,move)
      nextKey = tupleToBytes(nextState)


      newGcost = actualGCost + 1

      existingCost = bestCostToState.get(nextKey)  # if this path is better we push it

      if existingCost is None or newGcost < existingCost:
        bestCostToState[nextKey] = newGcost #update g
        parentRelations[nextKey] = (currentKey,move)  # parent pointer
        nextHuerisitc = HeuristicByCache(nextKey)
        nextfcost = newGcost + nextHuerisitc  #f' = g' + h'

        heapq.heappush(frontier, (nextfcost,nextHuerisitc,tieBreakerCount,nextKey))
        tieBreakerCount += 1

def applyCCWMoves(state:State,listOfMoves:list) -> State:
  for move in listOfMoves:
    state = rotateCounterClock(state,move[0])
  return state


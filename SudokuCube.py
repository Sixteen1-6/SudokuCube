def reverseRandomizer(state:State, listOfMoves:list) -> State:
  for move in reversed(listOfMoves):
    if move[1] == 1:
      state = rotateClock(state,move[0])
    else:
      state = rotateCounterClock(state,move[0])
  return state

# Returns face

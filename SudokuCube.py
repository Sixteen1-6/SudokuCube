# Rotate face clockwise function
def rotateClockData(face_data: tuple) -> tuple:
  row1 = face_data[0:3]
  row2 = face_data[3:6]
  row3 = face_data[6:9]
  newFace = (row3[0], row2[0], row1[0],
             row3[1], row2[1], row1[1],
             row3[2], row2[2], row1[2])
  return newFace

# Rotate face counter-clockwise function by rotating clockwise three times
def rotateCounterData(face_data: tuple) -> tuple:
  current = rotateClockData(face_data)
  current = rotateClockData(current)
  return rotateClockData(current)


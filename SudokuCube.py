def heuristic(state: State) -> int:
  # constants to help heuristic definition
  faceOrder = ['F','U','D','L','R','B']

  # duplicate checking heuristic function
  faceDupes = []
  countsByFace = {}
  for face in faceOrder:              # for each face count number of distinct digits
    faceData = getFace(face, state)
    distinct = [0] * 10               # list to keep track of digits 1-9 (index 1 maps to 1 in this case)
    for value in faceData:    # Iterate through indices instead of values
      distinct[value] +=1
    countsByFace[face] = distinct
    dupe = 0
    for digit in range(1,10):          # traverse distinct to count # of duplicates
      if distinct[digit] > 1:
        dupe += distinct[digit] - 1
    faceDupes.append(dupe)
# divide global by 12 (no. of stickers changed)
  hglobalMax = ceil(sum(faceDupes)/12)      # heuristic value for duplicates

  distancetoSurplus = 0
  for d in range (1,10):# digit index
    surplus = [i for i in faceOrder if countsByFace[i][d]>1] # Face of the surplus digit d
    deficit = [i for i in faceOrder if countsByFace[i][d]<1] # Face of the deficit digit d
    deficitDistance = len(deficit)
    notAdjacent = sum(1 for f in deficit if not any(num in surplus for num in ADJ[f] ))
    distancetoSurplus += (deficitDistance + notAdjacent)
  hAdjmoves = ceil(distancetoSurplus/12)  # each move can move 12 stickers between faces

  return max(hglobalMax,hAdjmoves)

